const T = (w: number, h: number, items: SketchItem[], caption?: L): Sketch => ({ view: 'top', w, h, items, caption });
const S = (w: number, h: number, items: SideItem[], caption?: L): Sketch => ({ view: 'side', w, h, items, caption });
const txt = (at: P, t: L | string, size = 11, anchor: 'start' | 'middle' | 'end' = 'middle'): SketchItem => ({ k: 'text', at, t, size, anchor });
const stxt = (at: P, t: L | string, size = 11, anchor: 'start' | 'middle' | 'end' = 'middle'): SideItem => ({ k: 'text', at, t, size, anchor });
const flag = (x: number, y: number): SketchItem => ({ k: 'hole', at: [x, y], flag: true });
/** player and ball, the player to the left of the ball (right-hander, target up) */
const me = (x: number, y: number, gap: number): SketchItem[] => [
  { k: 'player', at: [x - gap, y], face: 'right' },
  { k: 'ball', at: [x, y] },
];
const ground = (y = 0.3, w = 6): SideItem => ({ k: 'ground', pts: [[0, y], [w, y]] });

