// Screenshots of every Training screen (viewport, iPhone 13) for reports. Usage: node training-gallery.mjs <app url> <out dir>
import { webkit, devices } from 'playwright';

const url = process.argv[2] ?? 'http://localhost:5173/';
const out = process.argv[3] ?? '.';
const b = await webkit.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], locale: 'de-DE' });
const p = await ctx.newPage();
await p.goto(url);
await p.waitForTimeout(1200);
await p.evaluate(() => {
  localStorage.clear();
  sessionStorage.clear();
  localStorage.setItem('golfos.intro.v1', '1');
  localStorage.setItem('golfos.lang.v1', 'de');
  localStorage.setItem('golfos.profile.v1', JSON.stringify({ firstName: 'Sascha', lastName: 'Möscheit', hcpIndex: '12,4', homeClub: 'GC Hetzenhof' }));
  localStorage.setItem('golfos.training.fav.v1', JSON.stringify(['tiger-gate', 'landing-ring']));
});
await p.reload();
await p.waitForTimeout(800);
let n = 0;
const shot = async (name) => {
  await p.waitForTimeout(400);
  await p.screenshot({ path: `${out}/${String(++n).padStart(2, '0')}-${name}.png` });
};
const tab = (name) => p.locator('.tabbar button').filter({ hasText: name }).click();
await shot('start');
await p.locator('.module-card').filter({ hasText: 'Training' }).click();
await p.locator('.tr-cat').first().waitFor({ timeout: 30000 });
await shot('wissen');
await p.evaluate(() => window.scrollTo(0, 700));
await shot('themen');
await p.locator('.tr-cat').filter({ hasText: 'Putten' }).first().click();
await shot('thema-putten');
await p.getByRole('tab', { name: 'Grundlagen' }).click();
await shot('thema-grundlagen');
await p.getByRole('tab', { name: 'Fehler' }).click();
await shot('thema-fehler');
await p.getByRole('tab', { name: /^Übungen/ }).click();
await p.locator('.tr-drill-row .list-item').filter({ hasText: 'Tiger' }).click();
await shot('uebung');
// the drill page in tabs (17.10.2026): Zubehör and Ergebnis are their own tabs
await p.getByRole('tab', { name: 'Zubehör' }).click();
await p.waitForTimeout(300);
await shot('uebung-zubehoer');
await p.getByRole('tab', { name: 'Ergebnis' }).click();
await p.waitForTimeout(300);
await shot('uebung-ergebnis');
await p.getByRole('tab', { name: 'Anleitung' }).click();
await p.waitForTimeout(200);
await p.locator('.topbar .icon-btn').first().click();
await p.locator('.topbar .icon-btn').first().click();
// the 3D video of a swing (17.10.2026): from the front and from behind
await p.locator('.tr-cat').filter({ hasText: 'Drehung, Ablauf' }).first().click();
await p.locator('.tr-drill-row .list-item').filter({ hasText: '3:1' }).click();
await p.locator('.tr-motion-btn').first().click();
await p.locator('.tr-3d canvas').waitFor({ timeout: 30000 }).catch(() => {});
await p.waitForTimeout(2600);
await shot('3d-video');
await p.locator('.tr-3d-views .chip').filter({ hasText: 'Hinten' }).click();
await p.waitForTimeout(1500);
await shot('3d-video-hinten');
await p.locator('.topbar .icon-btn').first().click();
await p.locator('.topbar .icon-btn').first().click();
// the 3D fault videos of the night (18.10.2026): the slice from behind with the ball's tracer, the bunker, the putt at
// the hole from above – each a moment after the hit
const fault3d = async (cat, fault, name, wait, view) => {
  await p.locator('.tr-cat').filter({ hasText: cat }).first().click();
  await p.getByRole('tab', { name: 'Fehler' }).click();
  await p.locator('.list .list-item').filter({ hasText: fault }).first().click();
  await p.locator('figure.tr-sketch').first().scrollIntoViewIfNeeded();
  await p.locator('figure.tr-sketch .tr-motion-btn').first().click();
  await p.locator('.tr-3d canvas').waitFor({ timeout: 30000 }).catch(() => {});
  if (view) await p.locator('.tr-3d-views .chip').filter({ hasText: view }).click();
  await p.waitForTimeout(wait);
  await shot(name);
  await p.locator('.topbar .icon-btn').first().click();
  await p.locator('.topbar .icon-btn').first().click();
};
await fault3d('Drehung, Ablauf', 'Über die Ebene', '3d-slice-hinten', 4300);
await fault3d('Bunker', 'Ball bleibt im Bunker', '3d-bunker', 3600);
await fault3d('Putten', 'Ball startet rechts', '3d-putt-oben', 3000, 'Oben');
await tab('Üben');
await p.locator('.list-item').filter({ hasText: 'Putten 30 Min: Startlinie' }).click();
await p.getByRole('button', { name: 'Einheit starten' }).click();
await p.waitForTimeout(800);
await shot('einheit');
await p.locator('.hole-bar .map-score').click();
await shot('einheit-uebersicht');
await p.locator('.drawer-action').filter({ hasText: 'Pausieren' }).click();
await shot('ueben');
await p.evaluate(() => window.scrollTo(0, 600));
await shot('plaene');
await tab('Shop');
await p.waitForTimeout(1500);
await shot('shop');
await p.locator('.tr-product').first().locator('.tr-product-main').click();
await shot('produkt');
await p.getByRole('button', { name: 'In den Warenkorb' }).click();
await p.locator('.topbar .icon-btn').first().click();
await p.locator('.tr-cart-btn').click();
await shot('warenkorb');
await p.getByRole('button', { name: 'Zur Kasse' }).click();
await shot('kasse');
await tab('Verlauf').catch(() => {});
await b.close();
console.log(`${n} screenshots`);
